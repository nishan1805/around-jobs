#!/usr/bin/env node
// Turns the Figma export in design-tokens/figma-tokens.json into Tailwind v4
// theme variables (src/styles/tokens.generated.css) and the list of text-style
// utilities that `cn` needs to resolve class conflicts (src/lib/text-styles.generated.ts).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(readFileSync(join(root, "design-tokens/figma-tokens.json"), "utf8"));

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const rem = (px) => (px === 0 ? "0" : `${+(px / 16).toFixed(4)}rem`);

// "Primary Blue/Blue 500" -> "blue-500", "White/White" -> "white"
const paletteName = (figmaName) => slug(figmaName.split("/").pop());

// "Grey/Grey 100" -> "grey-100", "Text/On Brand" -> "text-on-brand"
const tokenName = (figmaName) => {
  const [group, leaf] = figmaName.split("/");
  return leaf.toLowerCase().startsWith(group.toLowerCase()) ? slug(leaf) : slug(`${group} ${leaf}`);
};

const isHex = (value) => /^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value);

const resolveRef = (ref) => {
  if (isHex(ref)) return ref;
  if (ref in source.colors) return `var(--palette-${paletteName(ref)})`;
  if (ref in source.tokens) return `var(--color-${tokenName(ref)})`;
  throw new Error(`Unknown colour reference "${ref}"`);
};

const lines = [];
const out = (line = "") => lines.push(line);

out("/*");
out(" * AUTO-GENERATED by scripts/generate-tokens.mjs. Do not edit by hand.");
out(` * Source: ${source.$source.file}`);
out(` * Exported: ${source.$source.exportedAt}`);
out(" * Re-sync: update design-tokens/figma-tokens.json, then run `npm run tokens`.");
out(" */");
out();
out("/* Figma collection \"Colors\": primitives. Not exposed as utilities; use the semantic tokens below. */");
out(":root {");
for (const [name, hex] of Object.entries(source.colors)) {
  out(`  --palette-${paletteName(name)}: ${hex}; /* ${name} */`);
}
out("}");
out();
out("@theme static {");
out("  /* Figma collection \"Tokens\" (Light mode) */");
out("  --color-*: initial;");
for (const [name, modes] of Object.entries(source.tokens)) {
  out(`  --color-${tokenName(name)}: ${resolveRef(modes.light)}; /* ${name} */`);
}
out();
out("  /* Figma fonts */");
for (const [family, role] of Object.entries(source.fonts)) {
  out(`  --font-${role}: var(--font-${slug(family)}), ui-sans-serif, system-ui, sans-serif; /* ${family} */`);
}
out();
out("  /* Figma text styles: one utility per style sets size, line height, weight and tracking */");
out("  --text-*: initial;");
const textStyleNames = [];
for (const [name, style] of Object.entries(source.textStyles)) {
  const key = slug(name);
  textStyleNames.push(key);
  const lineHeight = typeof style.lineHeight === "number" ? rem(style.lineHeight) : style.lineHeight;
  out(`  --text-${key}: ${rem(style.size)}; /* ${name} · ${style.family} */`);
  out(`  --text-${key}--line-height: ${lineHeight};`);
  out(`  --text-${key}--font-weight: ${style.weight};`);
  out(`  --text-${key}--letter-spacing: ${style.letterSpacing}em;`);
}
out();
out("  /* Figma collection \"Radius\" */");
out("  --radius-*: initial;");
for (const [name, px] of Object.entries(source.radius)) {
  out(`  --radius-${slug(name.replace(/^Radius-/, ""))}: ${rem(px)}; /* ${name} */`);
}
out();
const spacingValues = Object.values(source.spacing);
const gcd = (a, b) => (b === 0 ? a : gcd(b, a % b));
const spacingBase = spacingValues.reduce(gcd);
out(`  /* Figma collection "Spacing (8px)": every step (${spacingValues.join(", ")}) is a multiple of ${spacingBase}px, so p-1 = ${spacingBase}px, p-4 = ${spacingBase * 4}px, etc. */`);
out(`  --spacing: ${rem(spacingBase)};`);
out();
out("  /* Figma effect styles */");
out("  --shadow-*: initial;");
for (const [name, value] of Object.entries(source.shadows)) {
  out(`  --shadow-${slug(name.replace(/^Shadow-/, ""))}: ${value}; /* ${name} */`);
}
out("}");
out();
out("/* Figma collection \"Tokens\" (Dark mode). Applied when an ancestor has the `dark` class. */");
out(".dark {");
for (const [name, modes] of Object.entries(source.tokens)) {
  out(`  --color-${tokenName(name)}: ${resolveRef(modes.dark)};`);
}
out("}");

writeFileSync(join(root, "src/styles/tokens.generated.css"), `${lines.join("\n")}\n`);

const ts = [
  "// AUTO-GENERATED by scripts/generate-tokens.mjs. Do not edit by hand.",
  "export const textStyles = [",
  ...textStyleNames.map((name) => `  "${name}",`),
  "] as const;",
  "",
  "export type TextStyle = (typeof textStyles)[number];",
  "",
];
writeFileSync(join(root, "src/lib/text-styles.generated.ts"), ts.join("\n"));

console.log(
  `Generated ${Object.keys(source.colors).length} primitives, ${Object.keys(source.tokens).length} colour tokens, ` +
    `${textStyleNames.length} text styles, ${Object.keys(source.radius).length} radii, ${Object.keys(source.shadows).length} shadows.`,
);
